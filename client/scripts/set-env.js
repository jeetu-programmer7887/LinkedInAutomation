// Writes src/app/core/config/env.generated.ts from environment variables,
// so backend URLs are configured per deployment instead of hardcoded. Runs
// automatically before `npm start`, `npm run build`, `npm run watch` and
// `npm test` (see the "pre*" scripts in package.json).
//
//   API_URL        the deployed backend - used when the app is NOT opened on
//                  localhost. Vercel: Project Settings -> Environment Variables.
//   LOCAL_API_URL  the backend used when the app IS opened on localhost.
//                  Optional, defaults to http://localhost:3000.
//
// Either can also go in client/.env. Values are origins only - no trailing
// slash, no /api. The app picks between the two at runtime (api-config.ts).

const fs = require('fs');
const path = require('path');

const DEFAULT_LOCAL_API_URL = 'http://localhost:3000';

/** Minimal .env reader (KEY=value lines, # comments) - avoids a dotenv dependency. */
function readDotEnv(file) {
  if (!fs.existsSync(file)) return {};
  const vars = {};
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/i);
    if (match && !line.trim().startsWith('#')) {
      vars[match[1]] = match[2].replace(/^(['"])(.*)\1$/, '$2');
    }
  }
  return vars;
}

function origin(value) {
  return (value || '').trim().replace(/\/+$/, '').replace(/\/api$/, '');
}

const dotEnv = readDotEnv(path.join(__dirname, '..', '.env'));
const read = (name) => origin(process.env[name] || dotEnv[name]);

const localApiUrl = read('LOCAL_API_URL') || DEFAULT_LOCAL_API_URL;
const apiUrl = read('API_URL');

// A Vercel build without API_URL would ship a site that can't reach its
// backend - fail loudly instead.
if (!apiUrl && process.env.VERCEL) {
  console.error('[set-env] API_URL is not set. Add it in Vercel -> Project Settings -> Environment Variables.');
  process.exit(1);
}

const target = path.join(__dirname, '..', 'src', 'app', 'core', 'config', 'env.generated.ts');
const contents = `// Generated by scripts/set-env.js - do not edit, set API_URL / LOCAL_API_URL instead.
export const API_URL = ${JSON.stringify(apiUrl || localApiUrl)};
export const LOCAL_API_URL = ${JSON.stringify(localApiUrl)};
`;

fs.writeFileSync(target, contents);
console.log(`[set-env] API_URL = ${apiUrl || '(unset, using LOCAL_API_URL)'} · LOCAL_API_URL = ${localApiUrl}`);
