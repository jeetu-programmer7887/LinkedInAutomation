// Writes src/app/core/config/env.generated.ts from the API_URL environment
// variable. Runs automatically before `npm start`, `npm run build`,
// `npm run watch` and `npm test` (see the "pre*" scripts in package.json).
//
// API_URL is read from the environment (e.g. Vercel -> Project Settings ->
// Environment Variables), then client/.env, and falls back to the production
// backend - so a build always targets production unless told otherwise.
// For local development put API_URL=http://localhost:3000 in client/.env.
//
// Origin only - no trailing slash, no /api.

const fs = require('fs');
const path = require('path');

const PRODUCTION_API_URL = 'https://linked-in-automation-five.vercel.app';

/** Minimal .env reader (KEY=value lines, # comments) - avoids a dotenv dependency. */
function readDotEnv(file) {
  if (!fs.existsSync(file)) return {};
  const vars = {};
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/i);
    if (match && !line.trim().startsWith('#')) {
      vars[match[1]] = match[2].replace(/^(['"])(.*)\1$/, '$2');
    }
  }
  return vars;
}

const dotEnv = readDotEnv(path.join(__dirname, '..', '.env'));
const apiUrl = (process.env.API_URL || dotEnv.API_URL || PRODUCTION_API_URL)
  .trim()
  .replace(/\/+$/, '')
  .replace(/\/api$/, '');

const target = path.join(__dirname, '..', 'src', 'app', 'core', 'config', 'env.generated.ts');
const contents = `// Generated by scripts/set-env.js - do not edit, set API_URL instead.
export const API_URL = ${JSON.stringify(apiUrl)};
`;

fs.writeFileSync(target, contents);
console.log(`[set-env] API_URL = ${apiUrl}`);
